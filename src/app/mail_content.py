"""Allow email formatting while removing executable HTML and external CSS."""

import re
from html import escape
from html.parser import HTMLParser
from urllib.parse import urlsplit


STYLE_PROPERTIES = {
    "color", "background-color", "font-family", "font-size", "font-weight", "font-style",
    "text-align", "text-decoration", "text-indent", "line-height", "vertical-align",
    "list-style-type", "border", "border-width", "border-style", "border-color", "border-collapse",
    "width", "height", "max-width", "min-width", "margin", "margin-left", "margin-right",
    "margin-top", "margin-bottom", "padding", "padding-left", "padding-right", "padding-top",
    "padding-bottom", "float", "display", "white-space",
}


def clean_style(style):
    declarations = []
    for declaration in style.split(";"):
        name, separator, value = declaration.partition(":")
        name, value = name.strip().lower(), value.strip()
        if not separator or name not in STYLE_PROPERTIES:
            continue
        # No escapes, comments, URLs, CSS functions or executable expressions.
        # RGB colors are the sole supported function syntax generated by TinyMCE.
        simple = re.fullmatch(r"[a-zA-Z0-9#.,%'\" \-]+", value)
        rgb = name in {"color", "background-color", "border-color"} and re.fullmatch(
            r"rgba?\([\d.,% ]+\)", value, re.IGNORECASE
        )
        if simple or rgb:
            declarations.append(f"{name}: {value}")
    return "; ".join(declarations)


def safe_url(value, *, image=False):
    if any(ord(char) < 33 for char in value):
        return False
    if not image and re.fullmatch(r"#[\w-]+", value):
        return True
    try:
        url = urlsplit(value)
        return (url.scheme.lower() in {"http", "https"} and bool(url.hostname)) or (
            not image and url.scheme.lower() == "mailto" and bool(url.path)
        )
    except ValueError:
        return False


class MailHTML(HTMLParser):
    tags = {
        "p", "div", "br", "strong", "b", "em", "i", "u", "ul", "ol", "li", "a", "blockquote",
        "h1", "h2", "h3", "h4", "h5", "h6", "span", "s", "strike", "sub", "sup", "pre", "code",
        "hr", "img", "table", "caption", "colgroup", "col", "thead", "tbody", "tfoot", "tr",
        "th", "td", "figure", "figcaption",
    }
    void_tags = {"br", "hr", "img", "col"}
    blocked = {"script", "style", "iframe", "object", "svg", "math", "template"}
    numeric_attributes = {
        "img": {"width", "height"}, "table": {"width", "height", "border", "cellpadding", "cellspacing"},
        "td": {"width", "height", "colspan", "rowspan"}, "th": {"width", "height", "colspan", "rowspan"},
        "col": {"span", "width"}, "ol": {"start"}, "li": {"value"},
    }

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.output = []
        self.text = []
        self.suppressed = 0
        self.has_image = False

    def handle_starttag(self, tag, attrs):
        if tag in self.blocked:
            self.suppressed += 1
        if self.suppressed or tag not in self.tags:
            return
        attrs = dict(attrs)
        if tag == "img":
            if not safe_url(attrs.get("src") or "", image=True):
                return
            self.has_image = True
        attributes = {}
        for name, value in attrs.items():
            if value is None:
                continue
            if name == "style":
                value = clean_style(value)
                if not value:
                    continue
            elif name == "title" or (tag == "img" and name == "alt"):
                pass
            elif name == "dir" and value in {"ltr", "rtl", "auto"}:
                pass
            elif name == "id" and re.fullmatch(r"[\w-]+", value):
                pass
            elif tag == "a" and name == "href" and safe_url(value):
                pass
            elif tag == "img" and name == "src":
                pass
            elif name in self.numeric_attributes.get(tag, set()) and re.fullmatch(r"\d{1,5}%?", value):
                pass
            elif tag == "th" and name == "scope" and value in {"row", "col", "rowgroup", "colgroup"}:
                pass
            elif tag == "ol" and name == "type" and value in {"1", "a", "A", "i", "I"}:
                pass
            elif tag == "a" and name == "target" and value == "_blank":
                attributes["rel"] = "noopener noreferrer"
            else:
                continue
            attributes[name] = value
        serialized = "".join(f' {name}="{escape(value, quote=True)}"' for name, value in attributes.items())
        self.output.append(f"<{tag}{serialized}>")

    def handle_endtag(self, tag):
        if tag in self.blocked:
            self.suppressed = max(0, self.suppressed - 1)
            return
        if not self.suppressed and tag in self.tags and tag not in self.void_tags:
            self.output.append(f"</{tag}>")

    def handle_data(self, data):
        if not self.suppressed:
            self.output.append(escape(data))
            self.text.append(data)


def clean_mail_html(body):
    parser = MailHTML()
    parser.feed(body)
    parser.close()
    if not "".join(parser.text).replace("\u200b", "").strip() and not parser.has_image:
        raise ValueError("Podaj treść wiadomości.")
    return "".join(parser.output)
